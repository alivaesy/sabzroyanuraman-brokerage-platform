-- Initial empty feature table for Web GIS integration testing.
-- Safe to run once on the target database; creates no sample/business records.
BEGIN;

CREATE TABLE IF NOT EXISTS public.webgis_features (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL DEFAULT '',
    category TEXT NOT NULL DEFAULT 'test',
    geom geometry(Geometry, 4326) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS webgis_features_geom_gix
    ON public.webgis_features USING GIST (geom);

GRANT SELECT ON TABLE public.webgis_features TO sabzroyan_app;
GRANT USAGE, SELECT ON SEQUENCE public.webgis_features_id_seq TO sabzroyan_app;

COMMIT;
