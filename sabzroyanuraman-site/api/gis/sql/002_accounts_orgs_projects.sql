-- Phase 1 schema for Web GIS accounts, organizations, subscriptions and projects.
-- Structure only. No credentials, sample data, or privileges are created by this migration.
BEGIN;

CREATE TABLE IF NOT EXISTS public.gis_organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 2 AND 200),
    slug TEXT NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9][a-z0-9-]{1,62}$'),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended', 'closed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gis_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL UNIQUE CHECK (username = lower(username) AND username ~ '^[a-z0-9][a-z0-9._-]{2,63}$'),
    email TEXT UNIQUE,
    password_hash TEXT NOT NULL,
    display_name TEXT NOT NULL DEFAULT '' CHECK (length(display_name) <= 200),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'suspended', 'closed')),
    is_platform_admin BOOLEAN NOT NULL DEFAULT false,
    password_changed_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_login_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.gis_organization_members (
    organization_id BIGINT NOT NULL REFERENCES public.gis_organizations(id) ON DELETE RESTRICT,
    user_id BIGINT NOT NULL REFERENCES public.gis_users(id) ON DELETE RESTRICT,
    role TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'admin', 'editor', 'viewer', 'member')),
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('invited', 'active', 'suspended', 'removed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (organization_id, user_id)
);
CREATE INDEX IF NOT EXISTS gis_org_members_user_idx ON public.gis_organization_members(user_id, status);

CREATE TABLE IF NOT EXISTS public.gis_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT REFERENCES public.gis_organizations(id) ON DELETE RESTRICT,
    user_id BIGINT REFERENCES public.gis_users(id) ON DELETE RESTRICT,
    plan_code TEXT NOT NULL CHECK (plan_code ~ '^[a-z0-9_-]{2,40}$'),
    requested_days INTEGER NOT NULL DEFAULT 30 CHECK (requested_days BETWEEN 1 AND 3650),
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'active', 'expired', 'suspended', 'cancelled')),
    starts_at TIMESTAMPTZ,
    expires_at TIMESTAMPTZ,
    max_users INTEGER NOT NULL DEFAULT 1 CHECK (max_users BETWEEN 1 AND 10000),
    activated_by BIGINT REFERENCES public.gis_users(id) ON DELETE RESTRICT,
    activation_note TEXT NOT NULL DEFAULT '' CHECK (length(activation_note) <= 1000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((organization_id IS NOT NULL) <> (user_id IS NOT NULL)),
    CHECK (expires_at IS NULL OR starts_at IS NULL OR expires_at > starts_at)
);
CREATE INDEX IF NOT EXISTS gis_subscriptions_org_status_idx ON public.gis_subscriptions(organization_id, status, expires_at);
CREATE INDEX IF NOT EXISTS gis_subscriptions_user_status_idx ON public.gis_subscriptions(user_id, status, expires_at);

CREATE TABLE IF NOT EXISTS public.gis_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.gis_users(id) ON DELETE CASCADE,
    token_hash CHAR(64) NOT NULL UNIQUE CHECK (token_hash ~ '^[a-f0-9]{64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    ip_hash CHAR(64),
    user_agent TEXT NOT NULL DEFAULT '' CHECK (length(user_agent) <= 1000),
    CHECK (expires_at > created_at)
);
CREATE INDEX IF NOT EXISTS gis_sessions_user_expiry_idx ON public.gis_sessions(user_id, expires_at) WHERE revoked_at IS NULL;

CREATE TABLE IF NOT EXISTS public.gis_projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id BIGINT NOT NULL REFERENCES public.gis_organizations(id) ON DELETE RESTRICT,
    created_by BIGINT NOT NULL REFERENCES public.gis_users(id) ON DELETE RESTRICT,
    name TEXT NOT NULL CHECK (length(btrim(name)) BETWEEN 1 AND 200),
    description TEXT NOT NULL DEFAULT '' CHECK (length(description) <= 10000),
    project_data JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'archived', 'deleted')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id, organization_id)
);
CREATE INDEX IF NOT EXISTS gis_projects_org_updated_idx ON public.gis_projects(organization_id, updated_at DESC);

CREATE TABLE IF NOT EXISTS public.gis_project_features (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES public.gis_users(id) ON DELETE RESTRICT,
    name TEXT NOT NULL DEFAULT '' CHECK (length(name) <= 200),
    layer_name TEXT NOT NULL DEFAULT 'default' CHECK (length(layer_name) BETWEEN 1 AND 100),
    properties JSONB NOT NULL DEFAULT '{}'::jsonb,
    geom geometry(Geometry, 4326) NOT NULL CHECK (NOT ST_IsEmpty(geom) AND ST_IsValid(geom)),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT gis_project_features_project_org_fk
        FOREIGN KEY (project_id, organization_id)
        REFERENCES public.gis_projects(id, organization_id) ON DELETE CASCADE,
    UNIQUE (id, organization_id)
);
CREATE INDEX IF NOT EXISTS gis_project_features_geom_gix ON public.gis_project_features USING GIST (geom);
CREATE INDEX IF NOT EXISTS gis_project_features_project_layer_idx ON public.gis_project_features(project_id, layer_name);

CREATE TABLE IF NOT EXISTS public.gis_admin_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_user_id BIGINT REFERENCES public.gis_users(id) ON DELETE RESTRICT,
    organization_id BIGINT REFERENCES public.gis_organizations(id) ON DELETE RESTRICT,
    action TEXT NOT NULL CHECK (length(action) BETWEEN 1 AND 100),
    target_type TEXT NOT NULL CHECK (length(target_type) BETWEEN 1 AND 100),
    target_id TEXT NOT NULL DEFAULT '' CHECK (length(target_id) <= 200),
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS gis_admin_audit_created_idx ON public.gis_admin_audit_log(created_at DESC);

COMMIT;
